    <p class="mb-3">
        Ai sensi del Regolamento (UE) 2016/679 del Parlamento europeo e del Consiglio del 27 aprile 2016 recante la disciplina europea per la protezione delle persone fisiche con riguardo al trattamento dei dati personali, nonché alla libera circolazione di tali dati (General Data Protection Regulation, nel prosieguo "GDPR"), e nel rispetto del decreto legislativo 30 giugno 2003, n. 196, così come novellato dal decreto legislativo 10 agosto 2018, n. 101, si informa che i dati personali forniti formeranno oggetto di trattamento nel rispetto degli obblighi di riservatezza previsti dalla normativa sopra richiamata cui è tenuto il progetto.
    </p>
    
